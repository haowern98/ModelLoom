import { afterEach, expect, it, vi } from 'vitest';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { repository } from '../../tests/package-repository.js';
import {
  createFixtureVerifier,
  createRuntimeVerifier,
  packageEvidence,
  requireLivePackage,
} from './verifier.js';
import { inventory } from '../../tests/inventory-fixture.js';
const directories: string[] = [];
interface EditableFixture {
  signed: {
    version: number;
    roles: Record<string, { keyids: string[] }>;
    meta: Record<string, unknown>;
  };
}
// These shapes are only for JSON generated by the test repository, never product metadata parsing.
function edit(bytes: Buffer): EditableFixture {
  return JSON.parse(bytes.toString('utf8')) as EditableFixture;
}
afterEach(async () => {
  vi.restoreAllMocks();
  await Promise.all(
    directories.splice(0).map((directory) => rm(directory, { recursive: true, force: true })),
  );
});
async function setup(expires?: string) {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'modelloom-tuf-'));
  directories.push(dir);
  const repo = path.join(dir, 'repo'),
    state = path.join(dir, 'state');
  const signed = await repository(repo, inventory, expires);
  const verifier = createFixtureVerifier(signed.root);
  return { repo, state, signed, verifier };
}
it('verifies real signatures and inventory hash through the local-only client', async () => {
  const { repo, state, verifier } = await setup();
  const result = await verifier.verify(repo, state);
  expect(result.packageId).toBe('llama-cpu');
  expect(() => requireLivePackage(result)).toThrow('UNVERIFIED_PACKAGE');
});
it('rejects a forged capability and absent production trust root', () => {
  expect(() => requireLivePackage({ packageId: 'llama-cpu' })).toThrow('UNVERIFIED_PACKAGE');
  expect(() => createRuntimeVerifier()).toThrow('MISSING_TRUST_ROOT');
});
it('retains authority until signed expiry and rejects expiry or a backwards clock', async () => {
  const { repo, state, verifier } = await setup();
  const capability = await verifier.verify(repo, state);
  const evidence = packageEvidence(capability);
  const clock = vi.spyOn(Date, 'now');
  clock.mockReturnValue(evidence.verifiedAt + 60_000);
  expect(packageEvidence(capability).inventory.packageId).toBe('llama-cpu');
  clock.mockReturnValue(evidence.expires);
  expect(() => packageEvidence(capability)).toThrow('UNVERIFIED_PACKAGE');
  clock.mockReturnValue(evidence.verifiedAt - 1);
  expect(() => packageEvidence(capability)).toThrow('UNVERIFIED_PACKAGE');
});
it('rejects another root even when every package checksum is valid', async () => {
  const { repo, state } = await setup();
  const other = await setup();
  await expect(other.verifier.verify(repo, state)).rejects.toThrow('PACKAGE_VERIFICATION_FAILED');
});
it.each(['timestamp.json', 'snapshot.json', 'targets.json', 'inventory.json'])(
  'rejects tampered %s',
  async (name) => {
    const { repo, state, verifier } = await setup();
    await writeFile(
      path.join(repo, name),
      (await readFile(path.join(repo, name)))
        .toString()
        .replace('2099', '2098')
        .replace('llama-cpu', 'llama-gpu'),
    );
    await expect(verifier.verify(repo, state)).rejects.toThrow('PACKAGE_VERIFICATION_FAILED');
  },
);
it('rejects expired signed metadata', async () => {
  const { repo, state, verifier } = await setup('2020-01-01T00:00:00Z');
  await expect(verifier.verify(repo, state)).rejects.toThrow('PACKAGE_VERIFICATION_FAILED');
});
it('rejects metadata over one MiB before JSON parsing', async () => {
  const { repo, state, verifier } = await setup();
  await writeFile(path.join(repo, 'timestamp.json'), ' '.repeat(1024 * 1024 + 1));
  await expect(verifier.verify(repo, state)).rejects.toThrow('PACKAGE_VERIFICATION_FAILED');
});
it('does not reuse successful metadata when local repository metadata disappears', async () => {
  const { repo, state, verifier } = await setup();
  await verifier.verify(repo, state);
  await rm(path.join(repo, 'timestamp.json'));
  await expect(verifier.verify(repo, state)).rejects.toThrow('PACKAGE_VERIFICATION_FAILED');
});
it('rejects a clock older than the last successful verification', async () => {
  const { repo, state, verifier } = await setup();
  await verifier.verify(repo, state);
  await writeFile(path.join(state, 'clock.json'), JSON.stringify(Date.now() + 100000));
  await expect(verifier.verify(repo, state)).rejects.toThrow('PACKAGE_VERIFICATION_FAILED');
});
it('rejects signed timestamp rollback after a newer version succeeds', async () => {
  const { repo, state, verifier, signed } = await setup();
  const original = await readFile(path.join(repo, 'timestamp.json'));
  const envelope = edit(original);
  envelope.signed.version = 2;
  await writeFile(path.join(repo, 'timestamp.json'), signed.envelope(envelope.signed, [3]));
  await verifier.verify(repo, state);
  await writeFile(path.join(repo, 'timestamp.json'), original);
  await expect(verifier.verify(repo, state)).rejects.toThrow('PACKAGE_VERIFICATION_FAILED');
});
it('retains verified root rotation for offline revalidation without trusting a cached root directly', async () => {
  const { repo, state, verifier, signed } = await setup();
  const root = edit(signed.root);
  root.signed.version = 2;
  const nextKey = root.signed.roles.root!.keyids[2]!;
  for (const role of ['timestamp', 'snapshot', 'targets'])
    root.signed.roles[role]!.keyids = [nextKey];
  await writeFile(path.join(repo, '2.root.json'), signed.envelope(root.signed, [0, 1]));
  const targets = edit(await readFile(path.join(repo, 'targets.json')));
  const targetBytes = signed.envelope(targets.signed, [2]);
  await writeFile(path.join(repo, 'targets.json'), targetBytes);
  const snapshot = edit(await readFile(path.join(repo, 'snapshot.json')));
  snapshot.signed.meta['targets.json'] = signed.digest(targetBytes);
  const snapshotBytes = signed.envelope(snapshot.signed, [2]);
  await writeFile(path.join(repo, 'snapshot.json'), snapshotBytes);
  const timestamp = edit(await readFile(path.join(repo, 'timestamp.json')));
  timestamp.signed.meta['snapshot.json'] = signed.digest(snapshotBytes);
  await writeFile(path.join(repo, 'timestamp.json'), signed.envelope(timestamp.signed, [2]));
  await verifier.verify(repo, state);
  await rm(path.join(repo, '2.root.json'));
  const capability = await verifier.verify(repo, state);
  expect(capability.packageId).toBe('llama-cpu');
});
